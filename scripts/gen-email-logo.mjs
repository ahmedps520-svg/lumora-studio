/**
 * Writes src/lib/email/logo.generated.ts: the app icon as a small PNG (base64)
 * that account emails embed inline, so the logo shows without loading anything.
 *   node scripts/gen-email-logo.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import sharp from "sharp";

const svg = readFileSync("src/app/icon.svg");
const png = await sharp(svg, { density: 384 })
  .resize(96, 96)
  .png({ compressionLevel: 9 })
  .toBuffer();
writeFileSync(
  "src/lib/email/logo.generated.ts",
  `/* Generated by scripts/gen-email-logo.mjs from src/app/icon.svg. Do not edit. */\n` +
    `export const EMAIL_LOGO_PNG_BASE64 =\n  ${JSON.stringify(png.toString("base64"))};\n`,
);
// eslint-disable-next-line no-console -- command-line output
console.log(`Wrote the email logo (${png.length} bytes).`);
