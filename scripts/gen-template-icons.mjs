const pascal = (name) =>
  name
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");

const out = {};
for (const name of ICONS) {
  const Icon = lucide[pascal(name)];
  if (!Icon) throw new Error(`Unknown icon: ${name}`);
  const markup = renderToStaticMarkup(createElement(Icon));
  const inner = markup.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "");
  out[name] = inner;
}

const body = Object.entries(out)
  .map(([name, inner]) => `  ${JSON.stringify(name)}: ${JSON.stringify(inner)},`)
  .join("\n");
writeFileSync(
  "src/lib/templates/icons.generated.ts",
  `/* Generated by scripts/gen-template-icons.mjs from Lucide (ISC licence). Do not edit. */\n` +
    `export const ICON_SVG: Record<string, string> = {\n${body}\n};\n`,
);
